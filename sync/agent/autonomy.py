# -*- coding: utf-8 -*-
"""
sync/agent/autonomy.py — лестница ступеней риска: сколько свободы заработала ПОЛОСА.

Недельный лимит не назначается числом, а зарабатывается. Угадать его до беты
нечем: доля попаданий агента неизвестна, а прошлый абсолют (50 000 ₽ на всё)
пропускал одну-две правки в неделю — за всё время движок записи применил девять
действий (разбор — writer/exposure.py). Поэтому право тратить риск даётся долей
недельного расхода кабинета и растёт по послужному списку: 0 % → 1 % → 3 % → 6 %.
При недельном расходе ≈ 5,7 млн ₽ (кабинет EDU, август 2026) ступень 1 — это
57 тыс ₽ на полосу, ступень 3 — 342 тыс ₽.

Ступень считается по track record САМОЙ ПОЛОСЫ, не агента целиком: полоса
минусовки может заслуженно стоять наверху, пока полоса запуска сидит в тени.

Три правила, без которых лестница разгонится не туда:

  1. Ступень 0 — не низшая ступень лестницы, а режим приёмки нового рычага.
     Применений в тени нет → закрытых наблюдений не появится → автоматический
     переход 0 → 1 логически невозможен, полоса заперлась бы навсегда. Из тени
     выпускает человек, прочитав на экране совпадения теневых намерений с
     фактом. Поэтому список теневых полос приходит аргументом (конфиг, решение
     Павла), а не лежит константой здесь: выпуск рычага не должен требовать
     правки кода и деплоя.

  2. Деньги важнее заявок. Полоса, у которой заявки выросли, а второй чекпоинт
     сказал обратное, выше ступени 1 не поднимается. Дешёвые плохие заявки —
     ровно тот исход, ради которого построен money_checkpoint
     (agent_e1_watchdog); лестница, растущая на одних заявках, обнулила бы его.
     Молчащий чекпоинт (ни одного успеха, проверенного деньгами) свидетельством
     против полосы не считается — но и права на ступень выше первой не даёт:
     ступени 2 и 3 требуют, чтобы сторож ВЫСКАЗАЛСЯ, а не просто промолчал.
     Полоса с блестящими заявками и молчащим чекпоинтом сидит на 1 % и
     продолжает применять — то есть сама нарабатывает сторожу материал.

  3. Падение мгновенное, подъём медленный. Свежий провал роняет на ступень вниз
     в том же такте, не дожидаясь, пока накопленная история его переварит.
     Но не в тень: свежее окно в 12 наблюдений шумно, и плохая пара недель не
     должна стоить решения человека. Полоса садится на 1 % — минимальный живой
     след, на котором она может отыграться сама. В тень уводит только устойчивый
     сигнал: накопленная доля улучшений ниже порога ступени 1.

Модуль ничего не читает и никуда не пишет: переводит слот
learning_loop.track_record в число. Слот там ключуется видом действия
(action_kind), сборку по полосам делает вызывающий (writer/lanes.py, задача 4).
"""

from dataclasses import dataclass
from typing import Any, Dict, Iterable, Optional


@dataclass(frozen=True)
class Step:
    step: int
    share: float          # доля недельного расхода кабинета на полосу
    min_closed: int       # закрытых наблюдений
    min_hit_rate: float   # доля улучшений среди закрытых
    min_money_rate: float # доля успехов, подтверждённых вторым чекпоинтом


# Пороги — из §1.5 плана беты. Ступень 3 требует 48 закрытых: при такте раз в
# сутки и горизонте замера 7 дней это порядка двух месяцев боевой работы полосы,
# то есть в бету верхняя ступень не попадает по построению.
# Верхняя ступень требует доли улучшений выше остальных (65 % против 60 %):
# 6 % недельного расхода — это ≈ 342 тыс ₽ под непроверенными изменениями,
# и планка входа туда не может совпадать с планкой входа на 57 тыс ₽.
STEPS = (
    Step(0, 0.0, 0, 0.0, 0.0),
    Step(1, 0.01, 12, 0.60, 0.0),
    Step(2, 0.03, 24, 0.60, 0.50),
    Step(3, 0.06, 48, 0.65, 0.60),
)

# Свежее окно провала: доля улучшений ниже 40 % на последних 12 закрытых.
RECENT_WINDOW = 12
RECENT_FLOOR_HIT_RATE = 0.40

# Ниже этой ступени свежий провал не роняет — см. правило 3 в шапке.
DEMOTION_FLOOR = 1

# Полосы, которые лестница не поднимает НИКОГДА: право применять на них даёт
# только человек, ключом lane_steps панели.
#
# Полоса запуска здесь по двум причинам, и обе про арифметику самой лестницы.
# Первая: ступень 1 требует 12 закрытых наблюдений, а закрытое наблюдение
# запуска — это новая кампания, прожившая свой горизонт в 30 дней; двенадцать
# таких — три месяца при том, что запусков за такт бывает ноль. Лестница
# высказалась бы уже после беты. Вторая, и главная: цена ошибки здесь не
# отматывается. Удаление объектов запрещено инвариантом, поэтому «откат
# запуска» — это пауза новой кампании и возврат доноров, а потраченные ею
# деньги остаются потраченными. Право на такое решение не зарабатывается
# долей попаданий на других решениях.
#
# Строка, а не lanes.LANE_LAUNCH: lanes импортирует autonomy, и обратный
# импорт замкнул бы кольцо. Две строки держит вместе сторож в тестах
# (test_agent_writer_launch: имя полосы обязано совпадать).
MANUAL_RELEASE_LANES = frozenset({"launch"})


def share_of(step: int) -> float:
    """Доля недельного расхода кабинета, положенная ступени."""
    for candidate in STEPS:
        if candidate.step == step:
            return candidate.share
    # Приведение к ближайшей ступени выдало бы долю расхода по ошибке вызова.
    raise ValueError(f"неизвестная ступень автономии: {step!r}")


def is_shadow(lane: str, shadow_lanes: Optional[Iterable[str]]) -> bool:
    """Стоит ли полоса в тени по решению человека."""
    return bool(shadow_lanes) and str(lane) in set(shadow_lanes)


def step_of(lane: str, record: Optional[Dict[str, Any]],
            shadow_lanes: Optional[Iterable[str]] = None) -> int:
    """Ступень полосы: 0..3.

    shadow_lanes — те полосы, которые человек ещё не выпустил из тени. По
    умолчанию пусто: зашитый сюда список рычагов заморозил бы решение Павла в
    коде. Полоса без права применять и так не наберёт закрытых наблюдений и
    останется на нуле сама — список нужен для обратного случая: рычаг с уже
    накопленным послужным списком, который человек убрал в тень.
    """
    if is_shadow(lane, shadow_lanes):
        return 0
    if str(lane) in MANUAL_RELEASE_LANES:
        return 0

    record = record or {}
    closed = _number(record.get("closed"))
    if closed <= 0:
        return 0

    hit_rate = _number(record.get("improved")) / closed
    money_rate = _money_rate(record)

    step = 0
    for candidate in STEPS:
        if closed < candidate.min_closed or hit_rate < candidate.min_hit_rate:
            continue
        if candidate.min_money_rate > 0.0:
            # Молчание сторожа — не провал, но и не подтверждение. Пустить на
            # 3 % и 6 % расхода по одним заявкам значило бы обнулить второй
            # чекпоинт ровно там, где цена ошибки наибольшая.
            if money_rate is None or money_rate < candidate.min_money_rate:
                continue
        step = candidate.step

    if step > DEMOTION_FLOOR and _recent_failure(record):
        step -= 1
    return step


def _money_rate(record: Dict[str, Any]) -> Optional[float]:
    """Доля успехов, которые подтвердил второй чекпоинт.

    None — чекпоинт по этой полосе ещё ни одного успеха не оценил; выше
    ступени 1 такая полоса не поднимается (см. step_of). Знаменатель берётся
    по оценённым (confirmed + contradicted), а не по всем улучшениям: у сторожа
    своё окно дозревания, и успех, до которого он не дошёл, — не противоречие
    деньгам, а отсутствие данных.
    """
    confirmed = _number(record.get("money_confirmed"))
    judged = confirmed + _number(record.get("money_contradicted"))
    if judged <= 0:
        return None
    return confirmed / judged


def _recent_failure(record: Dict[str, Any]) -> bool:
    """Провал на свежем окне закрытых наблюдений.

    Полей recent_* в learning_loop.track_record сегодня нет (август 2026) — их
    добавит замер такта (Ф16). Их отсутствие означает «свежее окно не измерено»
    и понижением не считается: иначе лестница роняла бы все полосы каждый такт.
    """
    recent_closed = _number(record.get("recent_closed"))
    if recent_closed < RECENT_WINDOW:
        return False
    return _number(record.get("recent_improved")) / recent_closed < RECENT_FLOOR_HIT_RATE


def _number(value: Any) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0
