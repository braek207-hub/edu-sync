# -*- coding: utf-8 -*-
"""
sync/agent/computed.py — вычисляемые настройки (корректировки и расписание).

Это НЕ гипотезы. Корректировка по сегменту — оценка отношения конверсионности
сегмента к базовой, сжатая к 1 пропорционально объёму данных (эмпирический Байес).
Мало наблюдений → корректировка близка к нулю; много → близка к наблюдаемому отношению.

Почему не A/B: при ~450 оплатах в год на аккаунт тест каждой корректировки сжёг бы
всю пропускную способность экспериментов на то, что считается формулой.

МЕТРИКА КОНВЕРСИОННОСТИ — конверсии среза, делённые на клики сегмента:
  · корректировки по сегментам — Conversions из сегментного отчёта Директа
    (достижения целей кабинета, то есть эффективные лиды);
  · расписание — достижения целей по часам из Метрики.

Так было не всегда, и в этом был фундаментальный дефект: ожидаемые оплаты
раздавались по сегментам ПРОПОРЦИОНАЛЬНО ДОЛЕ КЛИКОВ, после чего
конверсионность = оплаты/клики давала всем сегментам среза ОДНО И ТО ЖЕ число.
Корректировки различались только весом байесовского сжатия — то есть сегменты
не различали вовсе. Порог по оплатам на уровне кампании всё равно недостижим
(ни одна из 84 кампаний его не проходит), поэтому честные конверсии Директа
лучше красиво размазанных оплат.

База берётся ИЗ ТОГО ЖЕ СРЕЗА (Σ конверсий / Σ кликов), а не приходит снаружи:
внешняя база в других единицах (оплаты вместо конверсий) делает отношение
бессмысленным, и это ровно тот класс ошибки, который здесь уже случался.

Два вырождения дают отказ от корректировок с явной причиной, а не тихие нули:
  1. в срезе нет ни одной конверсии — считать нечего;
  2. у всех сегментов среза конверсионность совпала — данные не несут информации
     о сегментах (сигнатура дефекта выше).
"""

from math import isclose, sqrt
from typing import Any, Dict, List, Optional, Tuple

# Априорный вес в СОБЫТИЯХ (достижениях цели), а не в наблюдениях: единица
# наблюдения у срезов разная — клик Директа у корректировок, визит сайта у
# расписания. Перевод в наблюдения делает prior_trials по базовой конверсии.
PRIOR_EVENTS = 2.0
# ДОЛЯ, а не проценты: 0.5 = ±50 %. Имя несёт единицу измерения намеренно —
# рядом живёт одноимённый по смыслу потолок в ПРОЦЕНТАХ
# (writer/guardrails.py::MODIFIER_CAP = 50), и одинаковые имена в разных
# шкалах уже роняли ветку смешением единиц: 0.5, прочитанное как проценты,
# режет корректировку до полупроцента, а 50, прочитанное как доля, разрешает
# пятикратную. Единица обязана читаться из имени, а не из комментария.
MODIFIER_CAP_RATIO = 0.5
MIN_SUPPORT = 30          # ниже этого числа кликов сегмент не выводим вовсе
# Допуск сравнения конверсионностей. Разброс меньше него — это шум округления
# double, а не различие сегментов: размазывание по доле кликов давало именно его.
CONV_REL_TOL = 1e-9

NO_CLICKS_REASON = "в срезе нет кликов"
NO_CONVERSIONS_REASON = (
    "в срезе нет ни одной конверсии — конверсионность сегментов не считается; "
    "проверить, что цели переданы в запрос отчёта и настроены в кабинете"
)
LOW_SUPPORT_REASON = f"ни один сегмент среза не набрал {MIN_SUPPORT} кликов"
DEGENERATE_REASON = (
    "конверсионность всех сегментов среза одинакова — данные не различают сегменты, "
    "корректировки были бы вырожденными (сюда же попадает срез с единственным "
    "сегментом выше порога: сравнивать не с чем)"
)


def prior_trials(base_conv: float, prior_events: float = PRIOR_EVENTS) -> float:
    """Априорный вес в наблюдениях среза — из веса в СОБЫТИЯХ и базовой конверсии.

    Точность оценки конверсии определяется числом СОБЫТИЙ, а не числом попыток:
    при p ≈ 1 % и n = 550 ожидается пять достижений, и это шум, сколько бы
    визитов за ними ни стояло. Априорный вес, заданный сразу в попытках,
    несёт разный объём информации в срезах с разной базовой конверсией — а
    срезы здесь именно разные: у корректировок ставок наблюдение это КЛИК
    Директа, у расписания — ВИЗИТ сайта, и час суток набирает их тысячами.
    Постоянные 50 попыток давали часу вес 0.999, то есть сжатие к базе было
    выключено ровно там, где достижений могло быть меньше десятка.

    PRIOR_EVENTS = 2 выбран так, чтобы при базовой конверсии 4 % (порядок
    величины кабинетов EDU: 37 252 достижения на 1 010 261 визит) получались
    прежние 50 попыток — то есть поведение корректировок на сегодняшней
    калибровке не меняется, а расходится там, где конверсия среза другая.
    """
    if base_conv <= 0:
        return float("inf")
    return prior_events / base_conv


def empirical_prior_trials(
    rows: List[Dict[str, Any]], conv_key: str,
) -> float:
    """Априорный вес В НАБЛЮДЕНИЯХ, выведенный из самого среза (эмпирический Байес).

    PRIOR_EVENTS — калибровочная константа: она не знает, различаются ли
    сегменты этого среза вообще. Сегмент с тысячей кликов получал вес 0.95
    независимо от того, есть ли в срезе сигнал, и корректировки гнались за
    шумом (аудит 2026-08-23).

    Приор выводится методом моментов: наблюдаемый разброс конверсий сегментов
    минус ожидаемый биномиальный шум даёт межсегментную дисперсию τ̂², а
    её пересчёт в наблюдения — n₀ = base(1−base)/τ̂². Смысл прямой: сегменты
    различаются сильно — n₀ мал, своим данным сегмента верим почти сразу;
    разброс объясняется шумом — τ̂² = 0, n₀ бесконечен, сжатие полное и
    корректировки нулевые. Это ровно то, что и должно происходить со срезом
    без сигнала.

    Меньше двух сегментов — разброса нет по определению: возвращается
    бесконечность (полное сжатие), а не калибровочная константа.
    """
    usable = [(int(r.get("clicks") or 0), float(r.get(conv_key) or 0.0))
              for r in rows if int(r.get("clicks") or 0) > 0]
    if len(usable) < 2:
        return float("inf")
    total_clicks = sum(n for n, _ in usable)
    total_conv = sum(c for _, c in usable)
    if total_clicks <= 0 or total_conv <= 0:
        return float("inf")
    base = total_conv / total_clicks
    if base >= 1.0:
        return float("inf")

    # Взвешенная по кликам дисперсия наблюдаемых конверсий и средний
    # биномиальный шум тех же сегментов. Веса — клики: сегмент с большей
    # выборкой и точнее, и важнее для базы.
    observed_var = sum(n * (c / n - base) ** 2 for n, c in usable) / total_clicks
    noise_var = sum(n * (base * (1.0 - base) / n) for n, _ in usable) / total_clicks
    tau2 = observed_var - noise_var
    if tau2 <= 0:
        return float("inf")
    return base * (1.0 - base) / tau2


def shrink_ratio(
    segment_conv: float, segment_n: int, base_conv: float,
    prior_weight: Optional[float] = None
) -> float:
    """Отношение конверсии сегмента к базовой, сжатое к 1 при малом объёме."""
    if segment_n <= 0 or base_conv <= 0:
        return 1.0
    weight_trials = prior_trials(base_conv) if prior_weight is None else prior_weight
    weight = segment_n / (segment_n + weight_trials)
    shrunk = weight * segment_conv + (1.0 - weight) * base_conv
    return shrunk / base_conv


def ratio_rel_error(segment_events: float, base_events: float) -> Optional[float]:
    """Относительная ошибка отношения «конверсия сегмента / база».

    Пуассоновский счёт: относительные дисперсии числителя и знаменателя
    складываются — √(1/n_сегмента + 1/n_базы), та же механика, что у лестницы
    (ladder.py). Ноль событий в сегменте — реальный сигнал (сегмент не
    конвертит), его ошибка оценивается сверху как одно событие, а не как
    бесконечность: иначе самые убедительные минус-сегменты объявлялись бы
    «неизвестными». Считается ДО сжатия: сжатие уменьшает дисперсию, поэтому
    ошибка сырой оценки — честная верхняя граница ошибки сжатой.
    """
    if base_events <= 0:
        return None
    return sqrt(1.0 / max(segment_events, 1.0) + 1.0 / base_events)


def bid_modifier_percent(ratio: float, cap: float = MODIFIER_CAP_RATIO) -> int:
    """Отношение → процент корректировки ставки, ограниченный потолком.

    cap — ДОЛЯ (0.5 = ±50 %), как MODIFIER_CAP_RATIO; результат — ПРОЦЕНТЫ.
    """
    raw = ratio - 1.0
    clipped = max(-cap, min(cap, raw))
    return int(round(clipped * 100))


def _conv_rate(row: Dict[str, Any], conv_key: str) -> float:
    clicks = int(row.get("clicks") or 0)
    return (float(row.get(conv_key) or 0.0) / clicks) if clicks > 0 else 0.0


def _all_equal(values: List[float]) -> bool:
    """Все конверсионности совпали (с точностью до шума double)."""
    first = values[0]
    return all(isclose(v, first, rel_tol=CONV_REL_TOL, abs_tol=0.0) for v in values)


def _emit(
    rows: List[Dict[str, Any]], kind_prefix: str, conv_key: str
) -> Tuple[List[Dict[str, Any]], Optional[str]]:
    """Срез → (строки настроек, причина отказа). Одно из двух всегда пусто."""
    total_clicks = sum(int(r.get("clicks") or 0) for r in rows)
    total_conv = sum(float(r.get(conv_key) or 0.0) for r in rows)
    if total_clicks <= 0:
        return [], NO_CLICKS_REASON
    if total_conv <= 0:
        return [], NO_CONVERSIONS_REASON

    base_conv = total_conv / total_clicks
    supported = [r for r in rows if int(r.get("clicks") or 0) >= MIN_SUPPORT]
    if not supported:
        return [], LOW_SUPPORT_REASON

    # Приор — из самого среза, а не из константы: сила сжатия обязана зависеть
    # от того, есть ли в срезе межсегментный сигнал. Считается по ВСЕМ строкам
    # среза, включая мелкие: они тоже свидетельствуют о разбросе, хотя своих
    # корректировок и не получают.
    prior_weight = empirical_prior_trials(rows, conv_key)

    # Единственный сегмент сравнивать не с чем — _all_equal на списке из одного
    # элемента истинно, и это правильный ответ: отношение к базе, которую этот же
    # сегмент и задаёт, даёт ровно 1, то есть нулевую корректировку без информации.
    conv_rates = [_conv_rate(r, conv_key) for r in supported]
    if _all_equal(conv_rates):
        return [], DEGENERATE_REASON

    out: List[Dict[str, Any]] = []
    for row, conv in zip(supported, conv_rates):
        clicks = int(row["clicks"])
        ratio = shrink_ratio(conv, clicks, base_conv, prior_weight=prior_weight)
        rel = ratio_rel_error(float(row.get(conv_key) or 0.0), total_conv)
        out.append({
            "setting_kind": f"{kind_prefix}:{row['segment_kind']}",
            "setting_key": str(row["segment_key"]),
            "value": float(bid_modifier_percent(ratio)),
            "support_n": clicks,
            "raw_value": round(ratio, 4),
            # Ошибка оценки едет со строкой до самого применения: слой
            # уверенности (Э2.3) решает по ней, применять ли действие.
            "rel_error": round(rel, 4) if rel is not None else None,
        })
    return out, None


def compute_segment_modifiers(
    rows: List[Dict[str, Any]],
) -> Tuple[List[Dict[str, Any]], Optional[str]]:
    """Корректировки по сегментам: устройство, пол, возраст, гео.

    Конверсионность — Conversions сегментного отчёта Директа на клики сегмента.
    """
    return _emit(rows, "bid_modifier", "conversions")


def compute_schedule(
    rows: List[Dict[str, Any]],
) -> Tuple[List[Dict[str, Any]], Optional[str]]:
    """Почасовой профиль — та же механика на достижениях целей из Метрики."""
    return _emit(rows, "schedule", "sum_p_pay")
