# -*- coding: utf-8 -*-
"""
sync/agent/writer/units.py — единственная граница конверсии единиц корректировки.

Внутри движка корректировка живёт ДЕЛЬТОЙ: 30 значит «+30 % к ставке», -20 —
«-20 %», 0 — «ничего не менять». Так считает Э0 (sync/agent/computed.py:
ratio - 1.0, коридор ±50), так же читает человек в журнале действий, и в этих
же единицах откалиброваны рельсы (guardrails.MODIFIER_CAP) и previous_state.

API Директа принимает КОЭФФИЦИЕНТ со 100 в роли нейтрали: 100 — «оставить как
есть», 130 — «+30 %», 70 — «-30 %», 0 — «ставка × 0», то есть максимальное
подавление сегмента. Конвенция зафиксирована в проверенном коде продукта
(EDU v2/lib/lime/direct-settings-labels.ts:180 — `const pct = value - 100`) и
в нашем же probe (probe_bidmodifiers.py:127 шлёт 110 как «+10 %»).

Смешение шкал молчаливое и потому опасное: дельта +30, ушедшая в API как есть,
означает ставку 30 % от исходной (то есть -70 %) — ошибки не будет, элемент
применится. Дельта -20 вылетает за допустимый диапазон, элемент отклоняется, и
по правилу переприменения отклонённое действие повторяется каждый прогон вечно.

Поэтому конверсия проведена ровно в двух функциях ниже и вызывается только на
границе с API: delta_to_api — при сборке тела запроса (apply.to_api_call,
rollback.rollback_payload), api_to_delta — при нормализации факта, прочитанного
из bidmodifiers.get (sync/agent_e1.py::_normalize_actual). Всё, что между ними,
оперирует дельтами и ничего о 100-базе не знает.
"""

from typing import Any

API_NEUTRAL = 100      # «ничего не менять» в шкале Директа
API_MIN = 0            # ставка × 0 — предел подавления, ниже Директ не принимает
API_MAX = 1300         # предел усиления в шкале Директа


def delta_to_api(delta: Any) -> int:
    """Дельта (-50…+50) → коэффициент Директа (50…150). Нейтраль: 0 → 100.

    Значение вне допустимого диапазона Директа — это не «корректировка
    посильнее», а признак того, что в функцию пришло уже сконвертированное
    число или число мимо рельсы: молча отправлять такое нельзя, потому что
    API либо отклонит элемент (и он будет переприменяться вечно), либо
    примет совсем не то, что имелось в виду.
    """
    value = API_NEUTRAL + int(delta)
    if not (API_MIN <= value <= API_MAX):
        raise ValueError(
            f"коэффициент {value} вне диапазона Директа {API_MIN}..{API_MAX} "
            f"(дельта {int(delta)} %)"
        )
    return value


def api_to_delta(value: Any) -> int:
    """Коэффициент Директа (100 = нейтраль) → дельта. 130 → 30, 70 → -30."""
    return int(value) - API_NEUTRAL
