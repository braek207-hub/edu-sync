# -*- coding: utf-8 -*-
"""
sync/agent/writer/tier.py — класс достоверности: платим ли за действие риском.

Полоса (writer/lanes.py) отвечает на «что двигаем», класс — на «насколько мы
уверены и надо ли за это платить». Две шкалы ортогональны и в одну не
сворачиваются: сужение гео с нулём конверсий живёт в полосе перераспределения
(меняет, куда кампания тратит те же деньги), а классом остаётся нулевым — оно
снимает деньги с огня, а не ставит под удар.

Четыре класса (§1.4 плана беты):

  0. Арифметика — утверждение о ПРОШЛОМ, а не прогноз: минус-фраза на запрос
     с расходом больше трёх CPA и нулём конверсий за зрелое окно, запрет
     площадки по тому же признаку. Применяется всегда, риском не платит.
  1. Измеренное — рычаг посчитал своё число: сдвиг бюджета по кривой
     насыщения, корректировка сегмента. Платит, применяется по ступени полосы.
  2. Ставка — основание есть, измерения нет: разведка, новая кампания, смена
     цели. Платит из разведочного кармана.
  3. Предложение — ни измерения, ни рычага: новая посадочная, новый оффер,
     смысловая гипотеза модели. НЕ ПРИМЕНЯЕТСЯ НИКОГДА, ни при какой ступени.

Почему класс 0 не платит риском. Это не послабление, а исправление
арифметики. Цена ошибки здесь — упущенная выгода на трафике, который за зрелое
окно не дал ни одной конверсии при расходе выше трёх CPA; это не ноль, но и не
«весь расход кампании», как у прогноза. Именно такие рекомендации составляют
большинство того, что генерится, и именно они сегодня стоят в очереди позади
корректировок (дефект d36d1c3). Ограничитель у них свой и не риск-бюджет, а
доля вырезаемого расхода за такт (lanes.HYGIENE_MAX_CUT_SHARE = 5 %, то есть
285 000 ₽ при недельном расходе 5,7 млн ₽ — замер 26.08.2026), чтобы сломанный
источник данных не вырезал кабинет за один проход.

Порядок проверок — от самого строгого к самому дешёвому, и он содержательный,
а не стилистический:

  1. предложение (рычага нет) — перебивает всё, включая признак разведки;
     иначе смысловая гипотеза модели, помеченная exploration, получила бы
     право тратить деньги из разведочного кармана;
  2. ставка (experiments.is_bet) — перебивает арифметику: у разведочного
     действия снят гейт уверенности, и похожесть на утверждение о прошлом его
     не возвращает;
  3. арифметика — только для видов, вырезающих трафик ПО ПОСТРОЕНИЮ;
  4. измерение — рычаг заявил обещание (writer/expectation.of);
  5. иначе ставка.

Чего модуль не делает. Не решает, применять ли действие, и не списывает риск:
класс — вход отбора (lanes.select, задача 7), а не сам отбор. И не заводит
второго порога «трёх CPA»: множитель берётся из objects.py, где по нему и
отбираются кандидаты, — две копии разъехались бы на первой правке одной из
них, и агент минусовал бы по одному правилу, а объяснял другим.
"""

from typing import Any, Dict, Optional

from sync.agent.experiments import is_bet
from sync.agent.objects import ZERO_CONVERSION_RULE_OF_THREE
from sync.agent.writer import expectation

TIER_ARITHMETIC = 0
TIER_MEASURED = 1
TIER_BET = 2
TIER_PROPOSAL = 3

ALL_TIERS = (TIER_ARITHMETIC, TIER_MEASURED, TIER_BET, TIER_PROPOSAL)

# Классы, которые платят риск-бюджетом полосы. Класс 0 не платит по построению
# (обратный знак риска), класс 3 не платит потому, что не применяется.
RISK_PAYING_TIERS = frozenset({TIER_MEASURED, TIER_BET})

# Классы, которые вообще доходят до кабинета. Тройка не входит ни при какой
# ступени: право применять у неё отсутствует, а не «пока не заработано».
APPLIED_TIERS = frozenset({TIER_ARITHMETIC, TIER_MEASURED, TIER_BET})

# Во сколько раз расход должен превысить цену конверсии, чтобы ноль конверсий
# стал утверждением о прошлом. Порог живёт в objects.py: там по нему отбираются
# сами кандидаты (minus_word_candidates: cpa = cost / 3 против cpa_limit).
CPA_MULTIPLE = ZERO_CONVERSION_RULE_OF_THREE

# Окно, короче которого «ноль конверсий» означает не ноль, а «не приехало».
# Лиды CRM приходят днями целиком, с лагом 2–4 дня и без дозревания (замер
# 21.08.2026, sync/agent/db.py: все 45 дней совпали, leads_added = 0). Две
# недели оставляют зрелой большую часть окна даже при лаге в четыре дня и
# закрывают недельную сезонность целиком; боевое окно кандидатов вдвое длиннее
# (objects.CANDIDATE_WINDOW_DAYS = 30) и проходит с запасом.
MATURE_WINDOW_DAYS = 14

# Виды, вырезающие трафик ПО ПОСТРОЕНИЮ, — только они могут оказаться классом 0.
# Полосой этот список не выражается: negative.remove_added живёт в той же
# полосе гигиены, но трафик ВОЗВРАЩАЕТ, и «ноль конверсий в прошлом» о его
# будущем не утверждает ничего. geo.set войдёт сюда вместе со своим рычагом
# (Ф14), когда действие сможет показать, что список регионов только сужается.
CUTTING_KINDS = frozenset({"negative.add", "placement.exclude"})

# Виды, у которых доказательство ПО ПОСТРОЕНИЮ снято не с этого объекта.
# Смена цели оптимизации обещает конверсию, которой у этой кампании никогда не
# было: число перенесено с соседней. Обещание при этом есть и оно проверяемо —
# то есть по общему правилу вид получил бы класс 1 «измеренное здесь» и
# заплатил бы риском как за измерение. Это занижение цены уверенности, и
# ошибка здесь стоит всей кампании: стратегия переучивается целиком.
TRANSFERRED_EVIDENCE_KINDS = frozenset({"goal.set", "strategy.set"})


def tier_of(action: Dict[str, Any],
            context: Optional[Dict[str, Any]] = None) -> int:
    """Класс достоверности действия: 0 — арифметика, 3 — предложение.

    context — контекст объекта прогона (доля сегмента, расход и цена лида); тот
    же, что у writer/expectation.of. Нужен там, где обещание ещё не заявлено в
    payload: класс обязан отвечать одинаково до и после expectation.attach,
    иначе порядок сборки плана снова решал бы за отбор.
    """
    declared = _declared(action)
    computed = _computed(action, context or {})
    # Объявленный класс вправе только ужесточить. Идея приносит свой класс
    # (задачи 12–15), и гипотеза модели остаётся предложением, даже надев форму
    # минус-фразы; обратное направление означало бы, что действие выписывает
    # себе освобождение от риска.
    return computed if declared is None else max(declared, computed)


def _declared(action: Dict[str, Any]) -> Optional[int]:
    raw = action.get("tier")
    if raw is None:
        return None
    value = int(raw)
    if value not in ALL_TIERS:
        raise ValueError(f"неизвестный класс достоверности: {raw!r}")
    return value


def _computed(action: Dict[str, Any], context: Dict[str, Any]) -> int:
    kind = str(action.get("action_kind") or "")
    if not _has_lever(kind):
        return TIER_PROPOSAL
    if is_bet(action):
        return TIER_BET
    if kind in TRANSFERRED_EVIDENCE_KINDS:
        return TIER_BET
    if kind in CUTTING_KINDS and _is_arithmetic(action.get("evidence")):
        return TIER_ARITHMETIC
    if expectation.of(action, context) is not None:
        return TIER_MEASURED
    return TIER_BET


def _has_lever(kind: str) -> bool:
    """Есть ли для вида действия рычаг записи вообще.

    Импорт полос ВНУТРИ функции. Кольцо lanes → switch → expectation уже
    существует и рвётся ленивым импортом на стороне expectation; потребитель
    класса — отбор внутри lanes (задача 7), и модульный импорт отсюда замкнул
    бы второе кольцо lanes → tier → lanes на полуинициализированном lanes.

    Карта полос знает и виды будущих рычагов (Ф14–Ф15) — это правильно: их
    класс считается уже сейчас, а к применению их пускает allow-лист
    guardrails, а не эта функция. Вид, не попавший в карту вовсе, рычага не
    имеет — то самое «ни измерения, ни рычага».
    """
    from sync.agent.writer import lanes

    if kind.startswith(lanes.PROPOSAL_KIND_PREFIX):
        return False
    return kind in lanes.LANE_OF_KIND


def _is_arithmetic(evidence: Optional[Dict[str, Any]]) -> bool:
    """Утверждение о прошлом: за зрелое окно нуль конверсий на трёх CPA.

    Три обязательных условия, и ни одно не смягчается: без основания класса 0
    не бывает вовсе (иначе его получало бы любое отсечение), конверсии на
    вырезаемом трафике переводят действие в прогноз «дороже, чем нам надо», а
    незрелое окно — это не ноль, а не приехало.
    """
    if not evidence:
        return False
    cost = _number(evidence.get("cost_rub"))
    conversions = _number(evidence.get("conversions"))
    baseline_cpa = _number(evidence.get("baseline_cpa"))
    window_days = _number(evidence.get("window_days"))
    if None in (cost, conversions, baseline_cpa, window_days):
        return False
    if conversions != 0 or baseline_cpa <= 0:
        return False
    if window_days < MATURE_WINDOW_DAYS:
        return False
    return cost > CPA_MULTIPLE * baseline_cpa


def _number(value: Any) -> Optional[float]:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if number == number else None   # NaN — то же «неизвестно»
