# -*- coding: utf-8 -*-
"""
sync/agent/writer/exposure.py — сколько денег ставит под удар КОНКРЕТНОЕ изменение.

Прежняя цена ошибки была «весь дневной расход кампании × горизонт замера», одна
и та же для любого действия. Арифметически это неверно, и цена неверности
измерена: корректировка «AGE_55 −43 %» в кампании 114057545 стоила 38 876 ₽ из
50 000 недельного лимита — 78 % бюджета риска за одно касание сегмента, который
тратит в кампании несколько процентов. Агент физически мог сделать одно-два
действия в неделю; за всё время их применено девять.

Но «планшеты −30 %» не ставит под удар весь расход кампании. Под ударом:
  * только ДОЛЯ объекта, которой изменение касается (сегмент, отсечённые фразы,
    запрещённые площадки), и
  * только та ЧАСТЬ этой доли, на которую изменение её двигает.
Ошибись мы в корректировке −43 % на сегменте, который берёт 4 % расхода, — потеря
измеряется процентами от расхода сегмента, а не всей кампанией.

Это НЕ ослабление защиты. Гарантия остаётся прежней («если каждое непроверенное
изменение окажется вредным, потери не выйдут за недельный лимит»), меняется
только арифметика её левой части: считаем дельту изменения вместо всего объекта.
Ослаблением было бы занижение дельты — поэтому все множители здесь взяты с
запасом в консервативную сторону, а неизвестная доля означает «весь объект»,
а не «ноль».

Потолок объекта (risk.py) остаётся: сумма дельт по кампании за окно не может
превысить её расход за горизонт замера. Больше, чем кампания тратит, потерять
на ней нельзя, сколько бы правок в неё ни внесли.
"""

from typing import Any, Dict, Optional, Tuple

# Насколько быстрее расхода сегмента меняется его расход при движении ставки.
# Корректировка +30 % поднимает цену клика не более чем на 30 %, но объём растёт
# вместе с ней (выигрывается больше аукционов), поэтому расход двигается быстрее
# коэффициента. Двойка — запас: замеров собственной эластичности по корректировкам
# у нас нет, а занижать дельту нельзя. При |Δ| ≥ 50 % доля упирается в единицу,
# то есть под ударом считается ВЕСЬ сегмент — так и должно быть: половинная
# корректировка перестраивает сегмент целиком.
BID_ELASTICITY = 2.0

# То же для целевого CPA. Цель — прямой регулятор объёма автостратегии, но
# реакция размазана по обучению стратегии, а не мгновенна.
TCPA_ELASTICITY = 1.5

MICROS = 1_000_000


def _clamp_share(value: float) -> float:
    """Доля объекта под ударом: от 0 до 1. Больше объекта потерять нельзя."""
    if value != value:  # NaN
        return 1.0
    return max(0.0, min(1.0, float(value)))


def bid_modifier_exposure(percent: int, segment_share: Optional[float]) -> Dict[str, Any]:
    """Корректировка ставки: доля сегмента × сила сдвига.

    segment_share — доля объекта (расхода или кликов), которую занимает сегмент.
    None значит «долю установить не удалось»: тогда под ударом считается весь
    объект. Молчаливая подстановка средней доли была бы дырой в гарантии — не
    отличить «сегмент маленький» от «мы не знаем, какой он».
    """
    if segment_share is None:
        return {"share": 1.0,
                "basis": "доля сегмента неизвестна — под ударом весь объект"}
    move = _clamp_share(abs(int(percent)) / 100.0 * BID_ELASTICITY)
    share = _clamp_share(float(segment_share)) * move
    return {"share": share,
            "basis": (f"сегмент {round(float(segment_share) * 100, 1)}% объекта "
                      f"× сдвиг {round(move * 100)}%")}


def schedule_exposure(percent_by_hour: Dict[str, int],
                      segment_share: Optional[float] = None) -> Dict[str, Any]:
    """Расписание: средний по суткам сдвиг ставки.

    Расписание меняет ставку во ВСЕЙ кампании, поэтому доля объекта здесь
    единица, а сила сдвига — среднее по 24 часам: часы без правки входят в
    среднее нулями, иначе профиль «одна ночная ставка −50 %» стоил бы как
    сплошное понижение. Распределение расхода по часам в действии не известно,
    поэтому часы считаются равновесными — при неравномерном расходе это может
    и завысить, и занизить оценку, и запас BID_ELASTICITY здесь работает
    против занижения.
    """
    if not percent_by_hour:
        return {"share": 0.0, "basis": "часы не заданы"}
    mean_abs = sum(abs(int(v)) for v in percent_by_hour.values()) / 24.0
    share = _clamp_share(mean_abs / 100.0 * BID_ELASTICITY)
    return {"share": share,
            "basis": f"средний сдвиг по суткам {round(mean_abs, 1)}%"}


def budget_exposure(target_rub_per_day: float,
                    current_rub_per_day: float) -> Dict[str, Any]:
    """Бюджетный лимит: под ударом РАЗНИЦА между новым лимитом и расходом.

    Вниз — теряем то, что перестаём тратить (и зарабатывать) сверх нового
    лимита. Вверх — рискуем ровно приростом: прежний расход уже был, он не
    становится сомнительным оттого, что потолок подняли.

    Считается в рублях в день напрямую, а не долей: у бюджета есть абсолютная
    величина сдвига, и переводить её в долю объекта — терять точность там, где
    она дана.
    """
    delta = abs(float(target_rub_per_day) - float(current_rub_per_day))
    return {"daily_rub": round(delta, 2),
            "basis": (f"лимит {round(float(target_rub_per_day))} ₽/дн против "
                      f"расхода {round(float(current_rub_per_day))} ₽/дн")}


def tcpa_exposure(target_cpa: float, current_cpa: float) -> Dict[str, Any]:
    """Целевой CPA: относительный сдвиг цели.

    Цель двигает объём кампании, а не сегмента, поэтому доля объекта единица,
    а сила сдвига — относительное изменение цели с запасом TCPA_ELASTICITY.
    Нулевая или неизвестная текущая цель — «весь объект»: делить не на что.
    """
    current = float(current_cpa or 0.0)
    if current <= 0:
        return {"share": 1.0,
                "basis": "текущая цель неизвестна — под ударом весь объект"}
    move = _clamp_share(abs(float(target_cpa) - current) / current * TCPA_ELASTICITY)
    return {"share": move,
            "basis": (f"цель {round(float(target_cpa))} ₽ против {round(current)} ₽ "
                      f"— сдвиг {round(move * 100)}%")}


def traffic_cut_exposure(cut_rub_per_day: float, what: str) -> Dict[str, Any]:
    """Минус-фразы и запреты площадок: под ударом ровно вырезанный трафик.

    Отсечение не разгоняет ставки и не двигает бюджет — оно убирает конкретный
    поток. Ошибка стоит того, что этот поток приносил бы; сколько он стоил,
    известно из отчёта, по которому кандидата и выбрали.
    """
    return {"daily_rub": round(max(0.0, float(cut_rub_per_day)), 2),
            "basis": f"{what}: {round(float(cut_rub_per_day))} ₽/дн вырезаемого трафика"}


def whole_object_exposure(reason: str) -> Dict[str, Any]:
    """Выключение кампании и всё, где под ударом объект целиком."""
    return {"share": 1.0, "basis": reason}


def daily_rub(exposure: Optional[Dict[str, Any]],
              object_daily_cost: float) -> Tuple[float, str]:
    """Экспозиция действия → рубли в день + основание для отчёта.

    Три источника, по убыванию точности: явная сумма (daily_rub), доля объекта
    (share), ничего (весь объект). Последнее — не ошибка, а честный ответ
    «долю установить не удалось»: так ведут себя действия рычагов, которые
    экспозицию ещё не заполняют, и гарантия для них остаётся прежней.
    """
    cost = max(0.0, float(object_daily_cost))
    if not exposure:
        return cost, "экспозиция не указана — под ударом весь объект"
    if exposure.get("daily_rub") is not None:
        return max(0.0, float(exposure["daily_rub"])), str(exposure.get("basis") or "")
    if exposure.get("share") is not None:
        return cost * _clamp_share(exposure["share"]), str(exposure.get("basis") or "")
    return cost, str(exposure.get("basis") or "экспозиция пуста")
