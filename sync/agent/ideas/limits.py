# -*- coding: utf-8 -*-
"""
sync/agent/ideas/limits.py — пределы, общие для всех генераторов идей.

Здесь живёт то, что у генераторов ОДИНАКОВО по смыслу. Копия такого предела
в каждом генераторе разъезжалась бы при первой же правке одной из копий, и
разъезд был бы невидимым: оба числа выглядят осмысленными, просто идеи одного
генератора вдруг судятся строже идей другого.

**Предел срока.** Эксперимент, которому на вердикт нужно больше квартала,
соревнуется уже не со своей гипотезой, а с сезоном: за это время меняются
спрос, конкуренты и сами кампании, и любой исход можно объяснить чем угодно.
Смысл предела один и тот же и у выноса связок в отдельную кампанию, и у
A/B-теста, поэтому и ручка одна.

Ручка, а не константа: у одного направления квартал ожидания бессмыслен, у
другого нормален, и решать это должен человек в настройках, а не автор кода.

**Порог окупаемости и парность величин.** Обе проверки ниже сравнивают одни и
те же две колонки — ожидание и цену проверки, — поэтому и живут рядом: разъедься
их правила, и одна и та же идея у порога считалась бы убыточной, а у контракта
полной.
"""

from typing import Any, Dict, Optional

MAX_HORIZON_KEY = "idea_max_horizon_days"
DEFAULT_MAX_HORIZON_DAYS = 90

UNPAIRED_REASON = (
    "смета без ожидания: {cost:.0f} ₽ цены проверки при непосчитанной выгоде "
    "— строка расхода, которую нечем окупить")

UNPROFITABLE_REASON = (
    "проверка дороже находки: ожидание {expected:.0f} ₽ против {cost:.0f} ₽ "
    "цены теста — идея не окупает собственный замер")


def _number(value: Any) -> Optional[float]:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if number == number else None   # NaN — то же «неизвестно»


def max_horizon(ctx: Optional[Dict[str, Any]]) -> int:
    """Сколько дней идее позволено занять — из настроек такта или по умолчанию."""
    config = (ctx or {}).get("config") or {}
    value = _number(config.get(MAX_HORIZON_KEY))
    if value is None or value <= 0:
        return DEFAULT_MAX_HORIZON_DAYS
    return int(value)


def unprofitable_reason(expected_rub: Any, test_cost_rub: Any) -> Optional[str]:
    """Причина снятия, если идея не окупает собственную проверку. Иначе None.

    **Порог не свой, а тождественный.** Очередь и так ранжируется отношением
    «ожидание ÷ цена проверки» (registry.rank), но пола у отношения не было, и
    очередь честно сортировала идеи, из которых ни одна не окупалась. Замер
    28.08.2026: у генератора proven 17 живых идей — Σ ожидания 2 669 ₽ против
    Σ цены проверки 22 094 ₽, окупается ноль. Лучшая идея очереди обещала
    431 ₽ при цене замера 473 ₽.

    Ноль в знаменателе — бесплатная проверка (идея опирается на уже собранные
    данные): она окупается любым неотрицательным ожиданием, и порог её не
    касается. Строгое «дороже», а не «не дешевле»: идея, ровно окупающая
    замер, ничего не приносит, но и ничего не стоит — снимать её значит
    спорить с округлением.

    Непосчитанная величина порогом не судится. Идея без сметы или без
    ожидания не «бесплатна» и не «бесценна» — она непроверяема этим правилом,
    и решает её судьбу очередь (rank отправляет такие в хвост), а не порог.
    Прочти незнание нулём — и генератор, забывший посчитать ожидание,
    выносился бы вперёд посчитанных или снимался бы весь скопом.
    """
    expected = _number(expected_rub)
    cost = _number(test_cost_rub)
    if expected is None or cost is None or cost <= 0:
        return None
    if expected > cost:
        return None
    return UNPROFITABLE_REASON.format(expected=expected, cost=cost)


def unpaired_reason(expected_rub: Any, test_cost_rub: Any) -> Optional[str]:
    """Причина отказа, если идея несёт смету при непосчитанном ожидании.

    **Считаем обе величины или ни одной.** Замер 29.08.2026 (прод,
    edu_agent_ideas): у генератора abtest 113 живых идей, Σ цены проверки
    108 946 589 ₽ — и ни у одной ожидания нет. Экран предложений при этом
    показывает сто тринадцать строк расхода без единой цифры выгоды, а
    очередь их даже не может отранжировать: registry.rank делит ожидание на
    цену, и вся эта сумма для порядка очереди — ноль информации. Хуже: сумма
    выглядит бюджетом такта, хотя это оборот кампаний, а не деньги, которыми
    агент платит за замер.

    **Правило несимметрично, и это не поблажка.** Смета — не «оценка ущерба
    вообще», а ровно то списание риск-бюджета полосы, которым такт записи
    оплачивает применение (writer/risk.action_risk; см. proven.py, где смета
    и есть его результат). Платят четыре полосы из семи
    (lanes.RISK_PAYING_LANES) и два класса из четырёх (tier.RISK_PAYING_TIERS);
    предложение человеку (класс 3, полоса proposal) не применяется вовсе, и
    платить ему нечем. Поэтому:

      * смета без ожидания — дефект: агент готов потратить риск-бюджет, не
        назвав, ради чего;
      * ожидание без сметы — законное состояние предложения. Генератор master
        (Мастер кампаний) считает переплату против цены лида кабинета и
        оставляет смету ПУСТОЙ намеренно: проверку делает человек руками в
        интерфейсе, риск-бюджет за неё не платит никто. Ноль там означал бы
        бесплатную проверку и вынес бы идею вперёд тех, кто свою смету
        посчитал (rank: ноль в знаменателе — бесконечность).

    Ноль в смете — тот же законный случай бесплатной проверки, что и в
    unprofitable_reason: тратить нечего, окупать нечего.
    """
    expected = _number(expected_rub)
    cost = _number(test_cost_rub)
    if cost is None or cost <= 0:
        return None
    if expected is not None:
        return None
    return UNPAIRED_REASON.format(cost=cost)


def closing_reason(expected_rub: Any, test_cost_rub: Any) -> Optional[str]:
    """Причина закрыть УЖЕ принятую строку реестра. Иначе None.

    Одна дверь на оба правила — для прохода по живому реестру
    (registry.sweep_open). Строка, принятая вчера по вчерашним правилам, не
    перестаёт быть убыточной оттого, что её генератор сегодня молчит: замер
    29.08.2026 показал в очереди две идеи proven с ожиданием 32 ₽ при цене
    замера 933 ₽ и 129 ₽ при 829 ₽ — порог их не тронул, потому что тронуть
    строку он может только в момент записи, а генератор перестал их находить.

    Порядок проверок — от дефекта к экономике: непарная строка судится
    первой, потому что её убыточность недоказуема (делить не на что), и
    сказать про неё «не окупает» значило бы придумать за генератор число.
    """
    return (unpaired_reason(expected_rub, test_cost_rub)
            or unprofitable_reason(expected_rub, test_cost_rub))
