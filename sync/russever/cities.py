# Символы, которые Директ считает «узкими»: в Заголовке 2 и Тексте до 15 таких
# сверх лимита, в Заголовке 1 считаются наравне со всеми.
NARROW = set('!,.;:"«»—–-')


def L(s: str, narrow_free: bool = False) -> int:
    """Длина строки по правилам Директа."""
    return len(s) - (sum(1 for c in s if c in NARROW) if narrow_free else 0)


def plural(n: int, one: str, few: str, many: str) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return one
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return few
    return many


