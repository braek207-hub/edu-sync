"""Заголовки, тексты и быстрые ссылки РСЯ по фазе.

Стиль задан Павлом дословно: восклицания, «Успей!», бренды, «Уникальные скидки
производителей». Название города удлиняет строку, поэтому у каждого шаблона —
цепочка запасных вариантов: берётся первый, влезающий в лимит, посыл сохраняется.
Точный отсчёт дней намеренно не пишем («последние дни», «пару дней»), иначе
тексты пришлось бы править ежедневно и каждый раз проходить модерацию заново.

Редакция 19.09.2026 (структура «модель Ханты-Мансийска»):
- слово «выставка» в объявлениях запрещено (Павел) — заменено на «РосСеверЭкспо»,
  «куртки от фабрик», «пуховики и парки от фабрик»;
- число брендов считается по составу города («4 бренда», «6 брендов»), а не «7»;
- порядок заголовков/текстов — по CTR за 10–16.09: сначала проверенные лучшие.
"""
import datetime as dt
from typing import List, Tuple

from .cities import L, phase, plural

TITLE_LIMIT = 56   # Заголовок 1: считаются все символы
TEXT_LIMIT = 81    # Текст: узкие символы не в счёт (до 15 сверх)
LINK_TITLE = 30
LINK_DESC = 60


def _pick(limit: int, narrow_free: bool, *variants: str) -> str:
    for s in variants:
        if L(s, narrow_free) <= limit:
            return s
    return "!!ПЕРЕБОР!! " + variants[-1]


def brands(C: dict) -> Tuple[str, str, str, str]:
    """(два бренда для заголовков, первый, до четырёх коротких для текстов, все — для ссылки).
    Источник — C["бренды"] из cities.py: у городов разный состав, бренд, которого нет
    в городе, в объявлении запрещён (Павел, 16.09.2026 — Bask в Мирном)."""
    все = [b.strip() for b in C["бренды"].split(",")]
    короткие = [b.replace("Bjorn Larsen", "Bjorn") for b in все]
    return ", ".join(короткие[:2]), короткие[0], ", ".join(короткие[:4]), ", ".join(все)


def brand_count(C: dict) -> str:
    n = len(C["бренды"].split(","))
    return f"{n} {plural(n, 'бренд', 'бренда', 'брендов')}"


