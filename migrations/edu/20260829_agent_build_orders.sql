-- Очередь нарядов билдеру (sync/agent/build_queue.py,
-- docs/BUILD-ORDER-QUEUE.md, задача B3 плана AGENT-THROUGHPUT-PLAN.md).
--
-- Что чинит. Наряд билдеру был написан и провалидирован (build_order.py), но
-- ехать ему было некуда: `campaign.create` вне allow-листа записи намеренно —
-- тело кампании собирает другой репозиторий, — а способа передать наряд туда
-- не существовало. Вынос лучших связок оставался предложением на экране, а не
-- циклом: обратной связи «собрал, вот campaign_id и день старта» не было, и
-- завести наблюдение за созданной кампанией агент не мог в принципе.
--
-- Почему отдельная таблица, а не колонка в edu_agent_ideas. Это единственная
-- таблица агента, которую читает ЧУЖОЙ репозиторий. Колонка в реестре идей
-- отдала бы ему весь контур решений и смешала бы два жизненных цикла: идея
-- закрывается вердиктом о ЗАМЫСЛЕ, наряд — фактом сборки, и они расходятся
-- (идею может отклонить человек, пока кампания по её наряду собирается).
--
-- order_id      — ключ, БЕЗ ДАТЫ (build_order.make_order_id). У реестра ровно
--                 одна открытая идея на (кабинет, вид, направление), а дата в
--                 ключе заводила бы новую кампанию каждым прогоном
--                 генератора, оставляя прежнюю тратить.
-- order_json    — ПРОВЕРЕННОЕ тело наряда (build_order.validate), а не
--                 исходный словарь генератора: билдер обязан собирать ровно
--                 то, что проверил валидатор, иначе проверка была о другом
--                 тексте.
-- status        — queued → taken → built | failed, плюс cancelled. Тело
--                 обновляется только в queued: собирать движущуюся цель
--                 нельзя — половина кампании оказалась бы собрана по одному
--                 составу фраз, а кросс-минусовка доноров по другому.
-- status_reason — почему статус такой. Наряд, закрывшийся молча, неотличим от
--                 наряда, до которого не дошли руки, и следующий прогон
--                 поставил бы его заново, не зная, что уже спрашивал.
-- campaign_id   — адрес созданного объекта. До ответа билдера его нет вовсе:
--                 Id появляется только после campaigns.add. Без него агенту
--                 нечего ни наблюдать, ни ставить на паузу откатом.
-- started_on    — день ПЕРВОЙ ОТКРУТКИ, не создания. Кампания создаётся на
--                 паузе (writer/launch.STATE_SUSPENDED), между созданием и
--                 включением стоит человек, и окно наблюдения, отсчитанное от
--                 создания, съело бы горизонт днями простоя. NULL законен и
--                 означает «собрана, но ещё не включена».
-- experiment_id — наблюдение в edu_agent_experiments. Заводится ТОЛЬКО вместе
--                 с датой старта: строка реестра без дня открутки обещала бы
--                 вердикт по окну, в котором не было ни одного дня показов.
CREATE TABLE IF NOT EXISTS edu_agent_build_orders (
  order_id      TEXT PRIMARY KEY,
  idea_id       TEXT,
  account       TEXT NOT NULL,
  kind          TEXT NOT NULL,
  level_slug    TEXT NOT NULL,
  campaign_name TEXT NOT NULL,
  direction     TEXT,
  status        TEXT NOT NULL DEFAULT 'queued',
  status_reason TEXT,
  order_json    JSONB NOT NULL,
  campaign_id   TEXT,
  started_on    DATE,
  experiment_id TEXT,
  queued_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Открытые наряды читает КАЖДЫЙ прогон билдера, а закрытые копятся без
-- предела: частичный индекс держит выборку размером с очередь, а не с
-- историей. Тот же довод, что у индекса открытых ставок в
-- edu_agent_experiments.
CREATE INDEX IF NOT EXISTS edu_agent_build_orders_open_idx
  ON edu_agent_build_orders (status)
  WHERE status IN ('queued', 'taken');

-- Две кампании на один наряд — двойной расход и общий аукцион у двух наших же
-- кампаний. Id приходит только с ответом билдера, поэтому индекс частичный: у
-- неотвеченных нарядов колонка пуста, и уникальность их не касается.
CREATE UNIQUE INDEX IF NOT EXISTS edu_agent_build_orders_campaign_idx
  ON edu_agent_build_orders (campaign_id)
  WHERE campaign_id IS NOT NULL;

-- Гранты anon/authenticated в этом проекте полные, и доступ держит только RLS
-- (sync/db.enable_rls_for_ddl, аудиты 20.08 и 27.08). Политик ноль: синк и
-- билдер ходят ролью postgres — она владелец и RLS обходит, пока не выставлен
-- FORCE.
ALTER TABLE edu_agent_build_orders ENABLE ROW LEVEL SECURITY;
