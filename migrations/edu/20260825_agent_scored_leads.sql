-- Счётчик лидов дня, у которых ML-скор оплаты вообще есть, — знаменатель
-- среднего p_pay в тормозе роста (sync/agent/quality.py).
--
-- Почему не eff_leads: скоринг идёт по поведению визита и требует client_id,
-- проставленного не на всех лендах. Лид без скора входит в sum_p_pay нулём,
-- поэтому sum_p_pay / eff_leads меряет ДОЛЮ скоренных лидов, а не качество
-- когорты: у кампании, нарастившей мобильный трафик, такое «качество» упадёт,
-- хотя трафик не изменился. Отношение scored_leads / eff_leads считается
-- отдельно и означает другое — исправность ingest'а поведения.
--
-- DEFAULT 0 на историю честен: прошлые строки пересчитываются синком фактов
-- в своём окне, а до пересчёта кампания выглядит «без наблюдений» и вердикта
-- о падении качества не получает — это лучше, чем вердикт по пустому месту.
ALTER TABLE edu_agent_facts
  ADD COLUMN IF NOT EXISTS scored_leads INTEGER NOT NULL DEFAULT 0;
